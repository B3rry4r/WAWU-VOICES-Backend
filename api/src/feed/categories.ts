export type CategorySeed = (typeof CATEGORIES)[number];

/** Best category (most keyword hits, board order on a tie) in the season and theme; else in the question text; else null. */
export function categoryFor(
  season: string,
  theme: string,
  text: string,
): string | null {
  const score = (hay: string) => {
    let best: { slug: string; hits: number } | null = null;
    for (const c of CATEGORIES) {
      const hits = c.words.filter((w) => hay.includes(w)).length;
      if (hits > 0 && (!best || hits > best.hits))
        best = { slug: c.slug, hits };
    }
    return best?.slug ?? null;
  };
  return (
    score(` ${season} ${theme}`.toLowerCase()) ??
    score(` ${text}`.toLowerCase())
  );
}
